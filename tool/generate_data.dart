// Generated tool to bundle data files into lib/src/data/embedded_data.g.dart
import 'dart:io';

void main() {
  final dataDir = Directory('data');
  if (!dataDir.existsSync()) {
    stderr.writeln('Error: data/ directory not found.');
    exit(1);
  }

  final files = [
    'romanization-auto-table.txt',
    'UnicodeDataOverwrite.txt',
    'romanization-table.txt',
    'Chinese_to_Pinyin.txt',
    'Scripts.txt',
    'NumProps.jsonl',
    'UnicodeDataProps.txt',
    'UnicodeDataPropsCJK.txt',
    'UnicodeDataPropsHangul.txt',
  ];

  final outBuf = StringBuffer();
  outBuf.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND');
  outBuf.writeln('// Generated by tool/generate_data.dart');
  outBuf.writeln(
    '// ignore_for_file: constant_identifier_names, unnecessary_raw_strings',
  );
  outBuf.writeln();

  for (final filename in files) {
    final file = File('data/$filename');
    if (!file.existsSync()) {
      stderr.writeln('Error: data/$filename not found.');
      exit(1);
    }
    final content = file.readAsStringSync();
    final varName = _toVarName(filename);
    outBuf.writeln('/// Embedded content of `$filename`.');
    outBuf.writeln('const String $varName = r\'\'\'');
    outBuf.write(content);
    if (!content.endsWith('\n')) outBuf.writeln();
    outBuf.writeln('\'\'\';');
    outBuf.writeln();
  }

  outBuf.writeln('/// Map of all 9 embedded resource files keyed by filename.');
  outBuf.writeln('const Map<String, String> embeddedResourceFiles = {');
  for (final filename in files) {
    final varName = _toVarName(filename);
    outBuf.writeln("  '$filename': $varName,");
  }
  outBuf.writeln('};');

  final outFile = File('lib/src/data/embedded_data.g.dart');
  outFile.writeAsStringSync(outBuf.toString());
  print(
    'Successfully generated ${outFile.path} (${outFile.lengthSync()} bytes)',
  );
}

String _toVarName(String filename) {
  final clean = filename.replaceAll(RegExp(r'[\.\-]'), '_');
  return '_data_$clean';
}
